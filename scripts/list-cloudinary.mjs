// Lists every image already in the Cloudinary account, grouped by folder,
// and writes the URLs to lib/heroImages.ts so the hero/products pages can
// render straight from the CDN.

import { v2 as cloudinary } from "cloudinary";
import { writeFile, readFile } from "node:fs/promises";
import { resolve } from "node:path";

const envRaw = await readFile(resolve(process.cwd(), ".env.local"), "utf8");
for (const line of envRaw.split(/\r?\n/)) {
  const m = line.match(/^([A-Z0-9_]+)\s*=\s*(.*)$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
}

cloudinary.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME?.trim(),
  api_key: process.env.CLOUDINARY_API_KEY?.trim(),
  api_secret: process.env.CLOUDINARY_API_SECRET?.trim(),
  secure: true,
});

// Search API returns asset_folder for dynamic folders; api.resources doesn't.
const all = [];
let next_cursor;
do {
  const res = await cloudinary.search
    .expression("resource_type:image")
    .max_results(500)
    .next_cursor(next_cursor)
    .execute();
  all.push(...res.resources);
  next_cursor = res.next_cursor;
} while (next_cursor);

console.log(`Found ${all.length} resources total.\n`);

// Videos are a separate resource_type, so the image search above never sees
// them. Pull the BaywoodsVid reel separately for the home video strip.
const videos = [];
let vcursor;
do {
  const res = await cloudinary.search
    .expression("resource_type:video")
    .max_results(500)
    .next_cursor(vcursor)
    .execute();
  videos.push(...res.resources);
  vcursor = res.next_cursor;
} while (vcursor);

const byFolder = new Map();
for (const r of all) {
  const folder = r.folder || r.asset_folder || "(root)";
  if (!byFolder.has(folder)) byFolder.set(folder, []);
  byFolder.get(folder).push(r);
}

for (const [folder, items] of [...byFolder.entries()].sort()) {
  console.log(`  ${folder}: ${items.length}`);
}

const images = all.filter((r) => r.resource_type === "image");
const fromFolder = (name) =>
  images
    .filter((r) => (r.folder || r.asset_folder) === name)
    .sort((a, b) => a.public_id.localeCompare(b.public_id))
    .map((r) => r.secure_url);

const heroPool = fromFolder("Baywoodstore/Baywoods images");

// Newest drop lives in its own Cloudinary folder. Emit its public_ids so the
// home contact-sheet can feature it through next-cloudinary <CldImage>.
const featuredPublicIds = images
  .filter((r) => (r.folder || r.asset_folder) === "new/BaywoodsAll")
  .sort((a, b) => b.public_id.localeCompare(a.public_id))
  .map((r) => r.public_id);

const brandFolders = [
  "nike",
  "adidas",
  "new-balance",
  "vans",
  "puma",
  "asics",
  "birkenstock",
  "timberland",
];
const productImages = {};
for (const brand of brandFolders) {
  productImages[brand] = fromFolder(`Baywoodstore/${brand}`);
}

const heroOut = resolve(process.cwd(), "lib", "heroImages.ts");
await writeFile(
  heroOut,
  `// Auto-generated by scripts/list-cloudinary.mjs — do not edit.\n` +
    `// ${heroPool.length} editorial / lookbook shots from Cloudinary "Baywoodstore/Baywoods images".\n\n` +
    `export const heroImages: string[] = ${JSON.stringify(heroPool, null, 2)};\n`
);

const productsOut = resolve(process.cwd(), "lib", "productImages.ts");
await writeFile(
  productsOut,
  `// Auto-generated by scripts/list-cloudinary.mjs — do not edit.\n` +
    `// Brand-bucketed product photography from Cloudinary "Baywoodstore/<brand>".\n\n` +
    `export const productImages: Record<string, string[]> = ${JSON.stringify(productImages, null, 2)};\n`
);

const featuredVideoIds = videos
  .filter((r) => (r.folder || r.asset_folder) === "BaywoodsVid")
  .sort((a, b) => b.public_id.localeCompare(a.public_id))
  .map((r) => ({ id: r.public_id, w: r.width, h: r.height }));

const videosOut = resolve(process.cwd(), "lib", "featuredVideos.ts");
const videoEntries = featuredVideoIds
  .map((v, i) => `  { publicId: ${JSON.stringify(v.id)}, width: ${v.w}, height: ${v.h}, label: "Baywoods reel ${i + 1}" },`)
  .join("\n");
await writeFile(
  videosOut,
  `// Auto-generated by scripts/list-cloudinary.mjs — do not edit.\n` +
    `// ${featuredVideoIds.length} clips from Cloudinary folder "BaywoodsVid",\n` +
    `// featured in the home video strip (next-cloudinary getCldVideoUrl + poster).\n\n` +
    `export interface FeaturedVideo {\n  publicId: string;\n  width: number;\n  height: number;\n  label: string;\n}\n\n` +
    `export const featuredVideos: FeaturedVideo[] = [\n${videoEntries}\n];\n`
);

const featuredOut = resolve(process.cwd(), "lib", "featuredMedia.ts");
const featuredEntries = featuredPublicIds
  .map((id, i) => `  { publicId: ${JSON.stringify(id)}, alt: "Baywoods new arrival ${i + 1}" },`)
  .join("\n");
await writeFile(
  featuredOut,
  `// Auto-generated by scripts/list-cloudinary.mjs — do not edit.\n` +
    `// ${featuredPublicIds.length} shots from Cloudinary folder "new/BaywoodsAll",\n` +
    `// featured on the home contact-sheet via next-cloudinary <CldImage>.\n\n` +
    `export interface FeaturedImage {\n  publicId: string;\n  alt: string;\n}\n\n` +
    `export const featuredImages: FeaturedImage[] = [\n${featuredEntries}\n];\n`
);

console.log(`\nWrote ${heroPool.length} hero URLs → lib/heroImages.ts`);
console.log(`Wrote ${featuredPublicIds.length} featured public_ids → lib/featuredMedia.ts`);
console.log(`Wrote ${featuredVideoIds.length} video public_ids → lib/featuredVideos.ts`);
for (const [brand, urls] of Object.entries(productImages)) {
  console.log(`  ${brand}: ${urls.length}`);
}
console.log(`Wrote brand index → lib/productImages.ts`);
